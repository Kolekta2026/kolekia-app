const DICT: Record<Lang, Record<Key, Entry>> = { tr, en };

export type TFunction = (key: Key, params?: Params) => string;

export type Currency = 'TRY' | 'USD' | 'EUR' | 'GBP';
export const CURRENCIES: Currency[] = ['TRY', 'USD', 'EUR', 'GBP'];

type I18n = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFunction;
  currency: Currency;
  setCurrency: (c: Currency) => void;
  reloadPrefs: () => Promise<void>;
};

const I18nContext = createContext<I18n | null>(null);

function deviceLang(): Lang {
  try {
    const locale = Intl.DateTimeFormat().resolvedOptions().locale ?? '';
    return locale.toLowerCase().startsWith('tr') ? 'tr' : 'en';
  } catch {
    return 'tr';
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const db = useSQLiteContext();
  const [lang, setLangState] = useState<Lang>(deviceLang);
  const [currency, setCurrencyState] = useState<Currency>(() => (deviceLang() === 'tr' ? 'TRY' : 'USD'));
  const [ready, setReady] = useState(false);

  // Dil ve para birimi tercihleri (yedekten geri yüklemeden sonra da yeniden okunur)
  const reloadPrefs = useCallback(async () => {
    const rows = await db.getAllAsync<{ key: string; value: string }>(
      "SELECT key, value FROM settings WHERE key IN ('language', 'currency')"
    );
    let effective: Lang = deviceLang();
    for (const r of rows) {
      if (r.key === 'language' && (r.value === 'tr' || r.value === 'en')) {
        setLangState(r.value);
        effective = r.value;
      }
      if (r.key === 'currency' && CURRENCIES.includes(r.value as Currency)) setCurrencyState(r.value as Currency);
    }
    // Alan adları görünen dile getirilir (eski sürümde ya da yedekte tek dilde kalmış olabilir)
    try { await localizeFields(db, effective, true); } catch {}
  }, [db]);

  useEffect(() => {
    reloadPrefs().finally(() => setReady(true));
  }, [reloadPrefs]);

  const setCurrency = useCallback((c: Currency) => {
    setCurrencyState(c);
    db.runAsync("INSERT OR REPLACE INTO settings (key, value) VALUES ('currency', ?)", c);
  }, [db]);

  const setLang = useCallback((l: Lang) => {
    const prev = lang;
    setLangState(l);
    db.runAsync("INSERT OR REPLACE INTO settings (key, value) VALUES ('language', ?)", l);
    if (prev === l) return;
    // Önce karşılığı bilinmeyen alanlar eski dille işaretlenir, sonra tüm alanlar yeni dile çevrilir
    (async () => {
      try {
        await localizeFields(db, prev, true);
        await localizeFields(db, l, false);
      } catch {}
    })();
  }, [db, lang]);

  const t = useCallback<TFunction>((key, params = {}) => {
    const entry = DICT[lang][key] ?? tr[key];
    return typeof entry === 'function' ? entry(params) : entry;
  }, [lang]);

  if (!ready) return null;
  return (
    <I18nContext.Provider value={{ lang, setLang, t, currency, setCurrency, reloadPrefs }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
